#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Visualize the 12 expert GP trajectories generated by generate_expert_gps.py.

Input:
    reports/expert_gp/expert_00.npz
    ...
    reports/expert_gp/expert_11.npz

Output:
    reports/expert_gp/plots/
        expert_00.png
        ...
        expert_11.png
        all_experts.png
        all_experts_axis0_axis1.png
        summary.txt

Important:
    The original Yaginuma plotting code uses:
        x = axis1
        y = axis0
    and reverses both displayed axes with:
        xlim([0.6, -0.2])
        ylim([0.4, -0.2])

    This script therefore creates:
      1) per-expert plots in the Yaginuma display convention,
      2) all_experts.png in the same convention,
      3) all_experts_axis0_axis1.png in a conventional
         x=axis0, y=axis1 view for debugging.

No robot or ManiSkill motion is performed.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


NUM_EXPERTS = 12


def parse_args():
    project_root = Path(__file__).resolve().parents[1]

    parser = argparse.ArgumentParser(
        description="Plot 12 generated Yaginuma expert GP trajectories."
    )

    parser.add_argument(
        "--input-dir",
        type=Path,
        default=project_root / "reports" / "expert_gp",
        help="Directory containing expert_00.npz ... expert_11.npz.",
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=project_root / "reports" / "expert_gp" / "plots",
        help="Directory where plot images are written.",
    )

    parser.add_argument(
        "--max-plot-points",
        type=int,
        default=3000,
        help=(
            "Maximum number of points plotted per expert. "
            "The saved GP trajectory is not modified; this only downsamples "
            "for rendering speed and readability."
        ),
    )

    parser.add_argument(
        "--dpi",
        type=int,
        default=180,
        help="PNG output resolution.",
    )

    return parser.parse_args()


def validate_expert_files(input_dir: Path):
    missing = []

    for expert_id in range(NUM_EXPERTS):
        path = input_dir / f"expert_{expert_id:02d}.npz"

        if not path.is_file():
            missing.append(path)

    if missing:
        raise FileNotFoundError(
            "Missing expert files:\n"
            + "\n".join(str(path) for path in missing)
        )


def load_expert(path: Path, expert_id: int):
    with np.load(path) as data:
        if "mean" not in data:
            raise KeyError(
                f"{path}: required key 'mean' was not found."
            )

        mean = np.asarray(
            data["mean"],
            dtype=np.float64,
        )

    if mean.ndim != 2 or mean.shape[1] != 2:
        raise RuntimeError(
            f"Expert {expert_id:02d}: "
            f"expected mean shape (N, 2), got {mean.shape}."
        )

    if mean.shape[0] < 2:
        raise RuntimeError(
            f"Expert {expert_id:02d}: "
            f"trajectory must contain at least 2 points."
        )

    if not np.all(np.isfinite(mean)):
        raise RuntimeError(
            f"Expert {expert_id:02d}: NaN or Inf detected in mean."
        )

    return mean


def sample_for_plot(mean: np.ndarray, max_plot_points: int):
    if max_plot_points <= 1:
        raise ValueError("--max-plot-points must be >= 2.")

    n = mean.shape[0]

    if n <= max_plot_points:
        return mean

    indices = np.linspace(
        0,
        n - 1,
        max_plot_points,
        dtype=np.int64,
    )

    return mean[indices]


def add_start_end(ax, start_xy, end_xy):
    ax.scatter(
        start_xy[0],
        start_xy[1],
        marker="o",
        s=55,
        label="start",
        zorder=3,
    )

    ax.scatter(
        end_xy[0],
        end_xy[1],
        marker="x",
        s=65,
        linewidths=2,
        label="end",
        zorder=3,
    )


def plot_single_yaginuma_view(
    expert_id: int,
    mean: np.ndarray,
    output_path: Path,
    max_plot_points: int,
    dpi: int,
):
    sampled = sample_for_plot(
        mean,
        max_plot_points,
    )

    # Original Yaginuma display convention:
    # x = axis1, y = axis0
    x = sampled[:, 1]
    y = sampled[:, 0]

    start_xy = np.array(
        [mean[0, 1], mean[0, 0]]
    )

    end_xy = np.array(
        [mean[-1, 1], mean[-1, 0]]
    )

    fig, ax = plt.subplots(
        figsize=(7, 6)
    )

    ax.plot(
        x,
        y,
        linewidth=1.6,
        label=f"Expert {expert_id:02d}",
    )

    add_start_end(
        ax,
        start_xy,
        end_xy,
    )

    ax.set_title(
        f"Expert {expert_id:02d} GP Trajectory"
    )

    ax.set_xlabel(
        "axis1 (Yaginuma horizontal axis)"
    )

    ax.set_ylabel(
        "axis0 (Yaginuma vertical axis)"
    )

    ax.grid(
        True,
        alpha=0.3,
    )

    ax.set_aspect(
        "equal",
        adjustable="box",
    )

    ax.legend()

    fig.tight_layout()

    fig.savefig(
        output_path,
        dpi=dpi,
        bbox_inches="tight",
    )

    plt.close(fig)


def plot_all_yaginuma_view(
    experts,
    output_path: Path,
    max_plot_points: int,
    dpi: int,
):
    fig, ax = plt.subplots(
        figsize=(9, 8)
    )

    for expert_id, mean in experts:
        sampled = sample_for_plot(
            mean,
            max_plot_points,
        )

        # Same convention as original Yaginuma plot:
        # x = axis1, y = axis0
        x = sampled[:, 1]
        y = sampled[:, 0]

        line, = ax.plot(
            x,
            y,
            linewidth=1.5,
            label=f"Expert {expert_id:02d}",
        )

        ax.scatter(
            mean[0, 1],
            mean[0, 0],
            marker="o",
            s=35,
            color=line.get_color(),
            zorder=3,
        )

        ax.scatter(
            mean[-1, 1],
            mean[-1, 0],
            marker="x",
            s=45,
            linewidths=1.8,
            color=line.get_color(),
            zorder=3,
        )

    ax.set_title(
        "All 12 Expert GP Trajectories\n"
        "Yaginuma display convention: x=axis1, y=axis0"
    )

    ax.set_xlabel(
        "axis1"
    )

    ax.set_ylabel(
        "axis0"
    )

    ax.grid(
        True,
        alpha=0.3,
    )

    ax.set_aspect(
        "equal",
        adjustable="box",
    )

    ax.legend(
        ncol=2,
        fontsize=8,
    )

    fig.tight_layout()

    fig.savefig(
        output_path,
        dpi=dpi,
        bbox_inches="tight",
    )

    plt.close(fig)


def plot_all_axis0_axis1(
    experts,
    output_path: Path,
    max_plot_points: int,
    dpi: int,
):
    """
    Debug view:
        x = axis0
        y = axis1

    This is NOT the plotting convention used in the original
    Trajectory_Generator.py. It is generated only to make the
    axis relationship explicit before mapping to ManiSkill TCP.
    """

    fig, ax = plt.subplots(
        figsize=(9, 8)
    )

    for expert_id, mean in experts:
        sampled = sample_for_plot(
            mean,
            max_plot_points,
        )

        x = sampled[:, 0]
        y = sampled[:, 1]

        line, = ax.plot(
            x,
            y,
            linewidth=1.5,
            label=f"Expert {expert_id:02d}",
        )

        ax.scatter(
            mean[0, 0],
            mean[0, 1],
            marker="o",
            s=35,
            color=line.get_color(),
            zorder=3,
        )

        ax.scatter(
            mean[-1, 0],
            mean[-1, 1],
            marker="x",
            s=45,
            linewidths=1.8,
            color=line.get_color(),
            zorder=3,
        )

    ax.set_title(
        "All 12 Expert GP Trajectories\n"
        "Debug view: x=axis0, y=axis1"
    )

    ax.set_xlabel(
        "axis0"
    )

    ax.set_ylabel(
        "axis1"
    )

    ax.grid(
        True,
        alpha=0.3,
    )

    ax.set_aspect(
        "equal",
        adjustable="box",
    )

    ax.legend(
        ncol=2,
        fontsize=8,
    )

    fig.tight_layout()

    fig.savefig(
        output_path,
        dpi=dpi,
        bbox_inches="tight",
    )

    plt.close(fig)


def write_summary(
    experts,
    output_path: Path,
):
    lines = [
        "12 Expert GP trajectory visualization summary",
        "",
        "Legend:",
        "  circle (o) = start",
        "  cross  (x) = end",
        "",
        "Per-expert start/end in stored [axis0, axis1] order:",
    ]

    for expert_id, mean in experts:
        start = mean[0]
        end = mean[-1]
        displacement = end - start
        distance = float(
            np.linalg.norm(displacement)
        )

        lines.append(
            (
                f"Expert {expert_id:02d}: "
                f"start=[{start[0]:+.6f}, {start[1]:+.6f}], "
                f"end=[{end[0]:+.6f}, {end[1]:+.6f}], "
                f"delta=[{displacement[0]:+.6f}, "
                f"{displacement[1]:+.6f}], "
                f"straight_distance={distance:.6f}"
            )
        )

    output_path.write_text(
        "\n".join(lines) + "\n",
        encoding="utf-8",
    )


def main():
    args = parse_args()

    input_dir = args.input_dir.resolve()
    output_dir = args.output_dir.resolve()

    print(
        "=== Plot 12 Expert GP Trajectories ==="
    )

    print(
        "input dir       :",
        input_dir,
    )

    print(
        "output dir      :",
        output_dir,
    )

    print(
        "max plot points :",
        args.max_plot_points,
    )

    validate_expert_files(
        input_dir
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    experts = []

    print(
        "\nLoading expert trajectories..."
    )

    for expert_id in range(NUM_EXPERTS):
        path = (
            input_dir
            / f"expert_{expert_id:02d}.npz"
        )

        mean = load_expert(
            path,
            expert_id,
        )

        experts.append(
            (expert_id, mean)
        )

        print(
            f"Expert {expert_id:02d}: "
            f"shape={mean.shape}, "
            f"start=[{mean[0,0]:+.6f}, {mean[0,1]:+.6f}], "
            f"end=[{mean[-1,0]:+.6f}, {mean[-1,1]:+.6f}]"
        )

    print(
        "\nCreating per-expert plots..."
    )

    for expert_id, mean in experts:
        output_path = (
            output_dir
            / f"expert_{expert_id:02d}.png"
        )

        plot_single_yaginuma_view(
            expert_id=expert_id,
            mean=mean,
            output_path=output_path,
            max_plot_points=args.max_plot_points,
            dpi=args.dpi,
        )

        print(
            f"saved: {output_path.name}"
        )

    all_output = (
        output_dir
        / "all_experts.png"
    )

    plot_all_yaginuma_view(
        experts=experts,
        output_path=all_output,
        max_plot_points=args.max_plot_points,
        dpi=args.dpi,
    )

    print(
        f"saved: {all_output.name}"
    )

    debug_output = (
        output_dir
        / "all_experts_axis0_axis1.png"
    )

    plot_all_axis0_axis1(
        experts=experts,
        output_path=debug_output,
        max_plot_points=args.max_plot_points,
        dpi=args.dpi,
    )

    print(
        f"saved: {debug_output.name}"
    )

    summary_path = (
        output_dir
        / "summary.txt"
    )

    write_summary(
        experts,
        summary_path,
    )

    print(
        f"saved: {summary_path.name}"
    )

    print(
        "\n=================================="
    )

    print(
        "EXPERT GP PLOTTING: PASS"
    )

    print(
        "No robot motion was performed."
    )

    print(
        "=================================="
    )


if __name__ == "__main__":
    main()
